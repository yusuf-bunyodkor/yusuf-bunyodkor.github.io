"""Turns OpenStreetMap data around the site into a compact JS module for the 3D map.

Usage: python build_map.py osm.json
Coordinates are local metres: x → east, y → north, origin = centre of the complex.
"""
import json, math, os, sys

SRC = sys.argv[1]
OUT = os.path.join(os.path.dirname(__file__), '..', 'assets', 'js', 'map-data.js')
R_BUILD, R_ROAD = 340, 380

data = json.load(open(SRC, encoding='utf-8'))['elements']
LA0, LO0 = 38.5600, 69.0150
KX = math.cos(math.radians(LA0)) * 111320
KY = 110540

def xy(la, lo):
    return ((lo - LO0) * KX, (la - LA0) * KY)

# --- Somoniyon avenue (main reference line) ---
ave = [e for e in data if e.get('tags', {}).get('name') == 'хиёбони Сомониён' and e['tags'].get('highway') == 'trunk']
ave_pts = [xy(g['lat'], g['lon']) for e in ave for g in e['geometry']]

def closest_on(pts, p):
    best = None
    for a, b in zip(pts, pts[1:]):
        dx, dy = b[0] - a[0], b[1] - a[1]
        L = dx * dx + dy * dy or 1
        t = max(0, min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / L))
        q = (a[0] + dx * t, a[1] + dy * t)
        d = math.dist(q, p)
        if not best or d < best[0]:
            best = (d, q, (dx / math.sqrt(L), dy / math.sqrt(L)))
    return best

school1 = xy(38.55905, 69.01404)
_, P0, D = closest_on(ave_pts, school1)
if D[0] < 0: D = (-D[0], -D[1])          # along the avenue towards north-east
N = (-D[1], D[0])                         # normal pointing to the north-west side
# site: next to School №1 along the avenue, on the same (north) side — from the general plan
C = (P0[0] + D[0] * 72 + N[0] * 34, P0[1] + D[1] * 72 + N[1] * 34)

def loc(la, lo):
    x, y = xy(la, lo)
    return (round(x - C[0], 1), round(y - C[1], 1))

def area(poly):
    return abs(sum(a[0] * b[1] - b[0] * a[1] for a, b in zip(poly, poly[1:] + poly[:1]))) / 2

buildings, roads, zones = [], [], []
for e in data:
    t = e.get('tags', {})
    if 'geometry' not in e:
        continue
    pts = [loc(g['lat'], g['lon']) for g in e['geometry']]
    if 'building' in t:
        if pts[0] == pts[-1]: pts = pts[:-1]
        cx = sum(p[0] for p in pts) / len(pts); cy = sum(p[1] for p in pts) / len(pts)
        if math.hypot(cx, cy) > R_BUILD or math.hypot(cx, cy) < 36:
            continue
        lv = t.get('building:levels')
        a = area(pts)
        if lv and lv.replace('.', '').isdigit(): h = float(lv) * 3.2
        elif t['building'] in ('apartments', 'residential'): h = 15
        elif t['building'] in ('school', 'college', 'university', 'hospital', 'public', 'commercial', 'retail', 'office'): h = 11
        elif t['building'] in ('garage', 'garages', 'shed', 'roof', 'kiosk'): h = 3.5
        else: h = 9 if a > 700 else 7 if a > 250 else 5
        buildings.append({'p': pts, 'h': round(h, 1)})
    elif 'highway' in t:
        w = {'trunk': 24, 'primary': 16, 'secondary': 13, 'tertiary': 11, 'residential': 7, 'unclassified': 7, 'service': 4, 'living_street': 6}.get(t['highway'])
        if not w:
            continue
        if min(math.hypot(*p) for p in pts) > R_ROAD:
            continue
        roads.append({'p': pts, 'w': w, 'n': t.get('name', '')})
    elif t.get('leisure') in ('stadium', 'pitch', 'track', 'park', 'garden', 'playground'):
        if pts[0] == pts[-1]: pts = pts[:-1]
        if min(math.hypot(*p) for p in pts) > R_BUILD:
            continue
        zones.append({'p': pts, 'k': 'green' if t['leisure'] in ('park', 'garden') else 'sport'})

# crossroads Fayzobod = Somoniyon × 20-solagii Istiqloliyat
cross = None
ist = [loc(g['lat'], g['lon']) for e in data if e.get('tags', {}).get('name') == 'кӯчаи 20-солагии Истиқлолият' for g in e['geometry']]
avl = [(round(x - C[0], 1), round(y - C[1], 1)) for x, y in ave_pts]
best = 1e9
for p in ist:
    d, q, _ = closest_on(avl, p)
    if d < best and math.hypot(*q) < 400: best, cross = d, q

POIS = [
    ('school', 38.55905, 69.01404),
    ('lyceum', 38.55855, 69.01333),
    ('kinder', 38.56103, 69.01498),
    ('stadium', 38.55811, 69.01595),
    ('college', 38.55951, 69.01702),
    ('bazaar', 38.56215, 69.01289),
    ('bank', 38.5596, 69.01879),
    ('pharmacy', 38.56252, 69.01478),
]
pois = {k: loc(la, lo) for k, la, lo in POIS}
if cross: pois['cross'] = (round(cross[0], 1), round(cross[1], 1))
dist = {k: round(math.hypot(*v)) for k, v in pois.items()}

# footprint of the complex: 50 × 22 m, long side along the avenue
hx, hy = 25, 11
corners = [(-hx, -hy), (hx, -hy), (hx, hy), (-hx, hy)]
site = [(round(D[0] * a + N[0] * b, 1), round(D[1] * a + N[1] * b, 1)) for a, b in corners]

js = ('/* generated by tools/build_map.py from OpenStreetMap data (© OpenStreetMap contributors) */\n'
      'window.MAP_DATA=' + json.dumps({'b': buildings, 'r': roads, 'z': zones, 'poi': pois, 'dist': dist,
                                       'site': site, 'axis': [round(D[0], 4), round(D[1], 4)]},
                                      ensure_ascii=False, separators=(',', ':')) + ';\n')
open(OUT, 'w', encoding='utf-8').write(js)
print('buildings', len(buildings), 'roads', len(roads), 'zones', len(zones), 'size', len(js) // 1024, 'KB')
print('dist', dist)
